import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

// lineHeight/letterSpacing are aliases to Spacing variables in Figma, e.g. "spacing/8".
type Scale = Record<string, { size: number; lineHeight: string; letterSpacing: string }>;
const src = JSON.parse(readFileSync(resolve("tokens/figma-tokens.json"), "utf8")) as {
  palettes: Record<string, string[]>;
  paletteStops: number[];
  singleColors: Record<string, string>;
  spacing: Record<string, number>;
  radius: Record<string, number>;
  iconSize: Record<string, number>;
  typography: {
    family: string;
    weights: Record<string, number>;
    scale: Scale;
    textStyles: Record<string, { sizes: number[]; weights: string[] }>;
  };
  shadows: Record<string, string[]>;
};

const outDir = resolve("src/tokens");
mkdirSync(outDir, { recursive: true });
const HEADER = "/* Generated by `npm run build:tokens` from tokens/. Do not edit by hand. */\n";

const slug = (s: string) =>
  s.toLowerCase().replace(/&/g, "").replace(/[\s/_]+/g, "-").replace(/[()]/g, "").replace(/-+/g, "-").replace(/^-|-$/g, "");
const px = (n: number) => (n === 0 ? "0" : `${n}px`);
const block = (decls: string[]) => `${HEADER}:root {\n${decls.map((d) => `  ${d}`).join("\n")}\n}\n`;
const write = (file: string, decls: string[]) => writeFileSync(resolve(outDir, file), block(decls));

// Primitives. Names are keyed by Figma name so semantic aliases can resolve to them.
const primitives = new Map<string, string>();
for (const [name, hexes] of Object.entries(src.palettes)) {
  hexes.forEach((hex, i) => primitives.set(`${name}/${src.paletteStops[i]}`, `#${hex}`));
}
for (const [name, hex] of Object.entries(src.singleColors)) primitives.set(name, `#${hex}`);
const primVar = (name: string) => `--ds-color-${slug(name.replace("B&W/Pure ", "").toLowerCase())}`;
write("primitives.css", [...primitives].map(([n, v]) => `${primVar(n)}: ${v};`));

// Semantic colors
const semantic = readFileSync(resolve("tokens/semantic-colors.txt"), "utf8")
  .split("\n").filter((l) => l.trim() && !l.startsWith("#"))
  .map((l) => l.split(" => ").map((s) => s.trim()) as [string, string]);
const semNames = new Set(semantic.map(([n]) => n));
const semVar = (name: string) => `--ds-color-${slug(name)}`;
const skipped: string[] = [];
const semDecls: string[] = [];
for (const [name, target] of semantic) {
  // Stray top-level tokens ("bg", "text", "stroke") are unnamespaced leftovers in Figma.
  if (!name.includes("/") || target === "?") { skipped.push(`${name} => ${target}`); continue; }
  if (primitives.has(target)) semDecls.push(`${semVar(name)}: var(${primVar(target)});`);
  else if (semNames.has(target)) semDecls.push(`${semVar(name)}: var(${semVar(target)});`);
  else skipped.push(`${name} => ${target} (target not found)`);
}
write("semantic.css", semDecls);

// Typography
const t = src.typography;
write("typography.css", [
  `--ds-font-family: "${t.family}", system-ui, -apple-system, "Segoe UI", sans-serif;`,
  ...Object.entries(t.weights).map(([k, v]) => `--ds-font-weight-${k}: ${v};`),
  ...Object.entries(t.scale).flatMap(([k, v]) => [
    `--ds-font-size-${k}: ${px(v.size)};`,
    `--ds-line-height-${k}: var(--ds-spacing-${v.lineHeight.split("/")[1]});`,
    `--ds-letter-spacing-${k}: var(--ds-spacing-${v.letterSpacing.split("/")[1]});`,
  ]),
]);

// Text styles: .ds-text-<category>-<size>-<weight>, matching the Figma text styles (52).
// Size/line-height/letter-spacing always use the scale tokens the Figma style is bound to.
const scaleBySize = new Map<string, string>();
for (const [k, v] of Object.entries(t.scale)) scaleBySize.set(`${k.split("-")[0]}/${v.size}`, k);
const rules: string[] = [];
let styleCount = 0;
for (const [cat, { sizes, weights }] of Object.entries(t.textStyles)) {
  for (const size of sizes) {
    const key = scaleBySize.get(`${cat}/${size}`);
    if (!key) throw new Error(`No type scale token for text style ${cat}/${size}`);
    const sizeVal = `var(--ds-font-size-${key})`;
    const lh = `var(--ds-line-height-${key})`;
    const ls = `var(--ds-letter-spacing-${key})`;
    for (const w of weights) {
      styleCount++;
      rules.push(
        `.ds-text-${cat}-${size}-${w} {\n  font-family: var(--ds-font-family);\n  font-size: ${sizeVal};\n  line-height: ${lh};\n  letter-spacing: ${ls};\n  font-weight: var(--ds-font-weight-${w});\n}`,
      );
    }
  }
}
writeFileSync(resolve(outDir, "text-styles.css"), `${HEADER}${rules.join("\n\n")}\n`);

write("spacing.css", Object.entries(src.spacing).map(([k, v]) => `--ds-spacing-${k}: ${px(v)};`));
write("radius.css", Object.entries(src.radius).map(([k, v]) => `--ds-radius-${k}: ${px(v)};`));
write("icon-size.css", Object.entries(src.iconSize).map(([k, v]) => `--ds-icon-size-${k}: ${px(v)};`));
write("shadows.css", Object.entries(src.shadows).map(([k, v]) => `--ds-shadow-${k}: ${v.join(", ")};`));

const files = ["primitives", "semantic", "typography", "spacing", "radius", "icon-size", "shadows", "text-styles"];
writeFileSync(resolve(outDir, "index.css"), `${HEADER}${files.map((f) => `@import "./${f}.css";`).join("\n")}\n`);

console.log(`✓ ${primitives.size} primitives, ${semDecls.length} semantic tokens, ${styleCount} text styles written to src/tokens/`);
if (skipped.length) console.warn(`! skipped ${skipped.length}:\n${skipped.map((s) => `  - ${s}`).join("\n")}`);
